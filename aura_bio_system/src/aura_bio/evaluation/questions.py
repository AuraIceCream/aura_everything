"""The AURA-Bio biology benchmark: ~450 curated questions with grading keys.

Coverage spans the 18 SRS subdomains, the SRS task types, and learner levels
from high school to research, including numerical items (checked with SymPy),
process-order items, and a set of adversarial items designed to bait
hallucination (asking about non-existent entities). Each item declares only the
checks that apply to it.

The questions are curriculum-grounded (school biology through undergraduate
Campbell/Alberts-level material) and are intended for the SRS 25 ablation:
baseline model, basic hybrid RAG, full pipeline, and finetuned+RAG.
"""

from __future__ import annotations

from .schema import AnswerKey, BenchmarkQuestion, Difficulty

_COUNTER = {"n": 0}


def q(
    question: str,
    subdomain: str,
    task_type: str,
    level: str,
    difficulty: str = "medium",
    *,
    include: tuple[str, ...] = (),
    avoid: tuple[str, ...] = (),
    steps: tuple[str, ...] = (),
    numeric: float | None = None,
    tol: float = 0.02,
    ref: str = "",
    accept: tuple[str, ...] = (),
    adversarial: bool = False,
    tags: tuple[str, ...] = (),
) -> BenchmarkQuestion:
    _COUNTER["n"] += 1
    return BenchmarkQuestion(
        id=f"bio-{_COUNTER['n']:04d}",
        question=question,
        subdomain=subdomain,
        task_type=task_type,
        level=level,
        difficulty=Difficulty(difficulty),
        adversarial=adversarial,
        tags=tags,
        answer_key=AnswerKey(
            must_include=include,
            must_avoid=avoid,
            ordered_steps=steps,
            numeric=numeric,
            numeric_tolerance=tol,
            reference_answer=ref,
            acceptable_answers=accept,
        ),
    )


